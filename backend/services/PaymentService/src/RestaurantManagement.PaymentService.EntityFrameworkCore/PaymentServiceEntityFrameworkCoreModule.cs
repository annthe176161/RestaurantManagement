using Volo.Abp.EntityFrameworkCore;
using Volo.Abp.EntityFrameworkCore.SqlServer;
using Volo.Abp.Modularity;

namespace RestaurantManagement.PaymentService.EntityFrameworkCore;

[DependsOn(typeof(PaymentServiceDomainModule), typeof(AbpEntityFrameworkCoreSqlServerModule))]
public class PaymentServiceEntityFrameworkCoreModule : AbpModule
{
    public override void ConfigureServices(ServiceConfigurationContext context)
    {
        Configure<AbpDbContextOptions>(options => options.UseSqlServer());
    }
}
